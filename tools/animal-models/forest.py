"""Forest biome animals for Create a Zoo (semi-realistic low-poly). Each animal faces -Z, feet at y = 0."""

import numpy as np

from organic import Beast, rot

BASE_ROWS = {"White": [(0, "#ffffff")], "Dark": [(0, "#17120f")]}


def clamp(v):
    return max(0.0, min(1.0, float(v)))


def dorsal(y0, y1, k=0.3):
    """Ramp position by height: belly (0) to back (1), nudged by the surface normal."""
    return lambda p, n: clamp((p[1] - y0) / (y1 - y0) + k * n[1])


def by_height(y0, y1):
    return lambda p, n: clamp((p[1] - y0) / (y1 - y0))


def beast(animal_id, name, rarity, ramps):
    return Beast(animal_id, name, rarity, {**BASE_ROWS, **ramps})


def legs(b, front, back, x_front, x_back, paint, foot, foot_paint, claws=None, spread=0.0):
    """Four legs. front/back: [(y, z, radius), ...] from shoulder/hip down to the ankle."""
    for tag, joints, x0 in (("F", front, x_front), ("B", back, x_back)):
        for s, S in ((1, "R"), (-1, "L")):
            x = s * x0
            with b.bone(f"Leg{tag}{S}", "Body", (x, joints[0][0], joints[0][1])):
                pts = [((x + s * spread * i / len(joints), y, z), r) for i, (y, z, r) in enumerate(joints)]
                if foot != "hoof":
                    (lx, ly, lz), lr = pts[-1]
                    pts.append(((lx, lr * 0.95, lz - lr * 0.3), lr * 0.95))
                b.chain(pts, paint)
                ax, ay, az = pts[-1][0]
                r = joints[-1][2]
                if foot == "hoof":
                    b.cone((ax, 0.0, az), (ax, ay + r * 0.2, az), r * 1.25, foot_paint, tip_radius=r * 0.95)
                else:
                    b.blob([((ax, r * 0.8, az - r * 0.6), (r * 1.35, r * 0.85, r * 1.8))], foot_paint)
                    if claws:
                        for dx in (-0.55, -0.18, 0.18, 0.55):
                            base = (ax + dx * r * 1.5, r * 0.35, az - r * 2.2)
                            b.cone(base, (base[0], 0.02, base[2] - r * 0.7), r * 0.18, claws)


